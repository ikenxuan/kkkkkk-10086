/**
 * 推送去重键的保留策略。
 *
 * 这两张缓存表（`AwemeCaches` / `DynamicCaches`）里的每一行都是一个「这条内容对这个群
 * 推过了」的去重键。清理它们时有一条硬约束：
 *
 *   **键的寿命必须长于内容留在接口返回里的时间。**
 *
 * 否则键先被删、内容还在列表里，下一轮就会把同一条内容当成新内容再推一遍。
 * 原来的实现只按年龄删（`createdAt` 早于 N 天），在两条没有时间窗兜底的路径上必然重复推：
 * B站直播场次（一场播只有一行，播多久这行就得活多久）、抖音喜欢/推荐列表（接口只给最新
 * 一页，没有「多久以前的不推」这道过滤）。把 1 天调成 7 天只是把引信拉长，治不了根。
 */

/**
 * 每个订阅目标（用户 × 群 [× 推送类型]）至少保留多少条最新的去重键。
 *
 * 取 100 的依据：这些列表接口一页都在 20 条上下，100 留了 5 倍余量，
 * 所以「内容还可能出现在列表里」的键绝不会被年龄清理删掉。同时它是个上界 ——
 * 退订、换群、改推送类型留下的陈旧行仍然会随年龄被回收，表不会无界增长。
 */
export const KEEP_PER_TARGET = 100
